#!/usr/bin/env node
// Create / refresh <project>/remotion for 3D scenes that render with Remotion + R3F
// (storyboard type "3d" with three.physics or three.postfx, or engine "remotion").
//   node new-remotion.mjs <project-dir> [--force-scene <id>]
// Writes src/brand.generated.ts and src/scenes.generated.ts from brand.json / storyboard, and
// src/scenes/<id>.tsx from the template for new scenes. Then: npm install in remotion/ (ask first, ~300 MB).
import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { TEMPLATE_DIR, isMain, loadProject, parseArgs, sceneEngine } from "./lib/project.mjs";
import { effectiveDuration } from "./lib/scenes.mjs";

const ident = (id) => `Scene_${id.replace(/[^a-zA-Z0-9]/g, "_")}`;

export function newRemotion(dir, { forceScene = null } = {}) {
  const project = loadProject(dir);
  const scenes = (project.storyboard?.scenes ?? []).filter((s) => sceneEngine(s, project.studio) === "remotion");
  const root = join(project.root, "remotion");
  const tpl = join(TEMPLATE_DIR, "remotion-project");
  const created = [];
  if (!existsSync(join(root, "package.json"))) {
    cpSync(tpl, root, { recursive: true, filter: (src) => !src.endsWith("_template.tsx") });
    created.push("remotion/");
  }
  mkdirSync(join(root, "src", "scenes"), { recursive: true });

  const { width, height, fps } = project.studio.format;
  const b = project.brand ?? {};
  writeFileSync(
    join(root, "src", "brand.generated.ts"),
    `// Generated by one-studio new-remotion.mjs from ${b.name} v${b.version}. Do not edit.\n` +
      `export const BRAND = ${JSON.stringify({ name: b.name, version: b.version, colors: b.colors, motion: b.motion, typography: b.typography }, null, 2)} as const;\n` +
      `export const FORMAT = ${JSON.stringify({ width, height, fps })} as const;\n`,
  );

  const template = readFileSync(join(tpl, "src", "scenes", "_template.tsx"), "utf8");
  for (const s of scenes) {
    const file = join(root, "src", "scenes", `${s.id}.tsx`);
    if (!existsSync(file) || forceScene === s.id) {
      writeFileSync(file, template.replace(/\{\{id\}\}/g, s.id));
      created.push(`src/scenes/${s.id}.tsx`);
    }
  }
  const imports = scenes.map((s) => `import { Scene as ${ident(s.id)} } from "./scenes/${s.id}";`).join("\n");
  const list = scenes
    .map((s) => `  { id: ${JSON.stringify(s.id)}, component: ${ident(s.id)}, durationInFrames: ${Math.round(effectiveDuration(project, s) * fps)} },`)
    .join("\n");
  writeFileSync(
    join(root, "src", "scenes.generated.ts"),
    `// Generated by one-studio new-remotion.mjs from storyboard.json. Do not edit.\n${imports}\n\nexport const SCENES: { id: string; component: React.FC<{ durationInFrames: number }>; durationInFrames: number }[] = [\n${list}\n];\n`,
  );
  return { root, scenes: scenes.map((s) => s.id), created, installed: existsSync(join(root, "node_modules")) };
}

if (isMain(import.meta.url)) {
  try {
    const args = parseArgs(process.argv.slice(2), { flags: ["help"], options: ["force-scene"] });
    if (args.help || !args._[0]) {
      console.log("usage: new-remotion.mjs <project-dir> [--force-scene <id>]");
      process.exit(args._[0] ? 0 : 1);
    }
    const r = newRemotion(args._[0], { forceScene: args["force-scene"] });
    console.log(`✓ ${r.root}: ${r.scenes.length} Remotion scene(s) ${r.scenes.join(", ")}`);
    for (const c of r.created) console.log(`  created ${c}`);
    if (!r.installed) console.log(`  next: ask the user, then (cd "${r.root}" && npm install)  (~300 MB, one time per project)`);
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}

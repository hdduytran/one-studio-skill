// One self-contained HTML page with every component of a kit, styled by a brand (fonts fall back to the
// brand's system stacks: the page must open anywhere, from file://, without the project's assets).
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { TEMPLATE_DIR } from "./project.mjs";
import { escapeHtml } from "./scenes.mjs";
import { brandToCss } from "../brand-to-css.mjs";
import { applyPreset } from "./presets.mjs";

// The template brand, optionally with a preset applied: what a kit's gallery uses outside a project.
export function galleryBrand(preset, { from } = {}) {
  const base = JSON.parse(readFileSync(join(TEMPLATE_DIR, "brand.json"), "utf8").replace(/\{\{name\}\}/g, "kit-gallery"));
  return preset ? applyPreset(base, preset, { from }) : base;
}

function brandCss(brand, brandPath) {
  const tmp = mkdtempSync(join(tmpdir(), "kit-gallery-"));
  try {
    const { logo, ...rest } = brand; // the page shows components, not the logo (and must not need its file)
    brandToCss({ brand: rest, brandPath, root: tmp }, { offline: true, assetsDir: tmp });
    return readFileSync(join(tmp, "brand.css"), "utf8").replace(/@font-face\s*\{[^}]*\}\s*/g, "");
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

export function kitGalleryHtml(kit, { brand, brandPath = join(tmpdir(), "brand.json"), lang = "vi" }) {
  const os = readFileSync(join(TEMPLATE_DIR, "hyperframes-project", "assets", "os.css"), "utf8");
  const cells = kit.components.map((c) => `    <div class="cell"><div class="name">${escapeHtml(c.name)}${c.title ? ` · ${escapeHtml(c.title)}` : ""}</div>
      <div class="os-kit" data-component="${c.name}">
${c.html.replace(/^\s*<!--[\s\S]*?-->\s*\n?/, "").trimEnd().split("\n").map((l) => (l ? `        ${l}` : l)).join("\n")}
      </div>
    </div>`).join("\n");
  return `<!doctype html>
<html lang="${lang}">
<head>
<meta charset="utf-8" />
<title>Kit ${escapeHtml(kit.name)}</title>
<!-- Generated by one-studio library.mjs --kit-gallery. Final state, no animation; brand: ${escapeHtml(brand.name ?? "")}. -->
<style>
${brandCss(brand, brandPath)}
</style>
<style>
${os}
</style>
<style data-kit="${kit.name}">
${kit.css}
</style>
<style>
  html, body { margin: 0; overflow: auto; }
  .os-scene { --w: 1920px; --h: 1080px; height: auto; min-height: 100vh; overflow: visible; padding: calc(60 * var(--u)); box-sizing: border-box; }
  .gallery { display: grid; grid-template-columns: repeat(3, 1fr); gap: calc(60 * var(--u)); align-items: start; }
  .cell > .name { font-family: var(--font-mono); font-size: calc(18 * var(--u)); color: var(--c-muted); margin-bottom: calc(18 * var(--u)); }
</style>
</head>
<body>
<div class="os-scene">
  <h1 class="os-h1">Kit ${escapeHtml(kit.name)}</h1>
  ${kit.about ? `<p class="os-muted" style="margin-bottom: calc(50 * var(--u))">${escapeHtml(kit.about)}</p>` : ""}
  <div class="gallery">
${cells}
  </div>
</div>
</body>
</html>
`;
}
